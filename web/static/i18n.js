'use strict';
// Language support shared by the dashboard and the login page.
//
// The source strings are Italian; I18N_EN maps each one to English. A string
// missing from the map is shown as it is. The choice is per browser
// (localStorage) and English is the default until someone picks a language.

const I18N_KEY = 'mycelium.lang';
const I18N_LANGS = ['en', 'it'];

function getLang() {
    try {
        const v = localStorage.getItem(I18N_KEY);
        if (I18N_LANGS.includes(v)) return v;
    } catch { /* storage blocked: default */ }
    return 'en';
}
function storeLang(lang) {
    try { localStorage.setItem(I18N_KEY, lang); } catch { /* not persisted */ }
}
const locale = () => (getLang() === 'it' ? 'it-IT' : 'en-GB');

// t('Uscita {name} aggiunta.', { name }) → the string in the current
// language, with {placeholders} filled in.
function t(s, vars) {
    let out = getLang() === 'en' && typeof I18N_EN !== 'undefined' && I18N_EN[s] !== undefined ? I18N_EN[s] : s;
    if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return out;
}

// translateStatic translates the page's fixed HTML: text nodes, the
// placeholder/title/aria-label attributes, and the innerHTML of elements
// marked data-i18n-html (sentences with inline markup). Originals are kept,
// so it can run again after a language change. Subtrees marked data-dyn are
// rendered by script and skipped.
const i18nTextSrc = new WeakMap();
function translateStatic(root = document.body) {
    const walk = el => {
        if (el.nodeType !== 1 || el.hasAttribute('data-dyn') || /^(SCRIPT|STYLE|svg|CODE|TEXTAREA)$/i.test(el.tagName)) return;
        for (const attr of ['placeholder', 'title', 'aria-label']) {
            if (!el.hasAttribute(attr)) continue;
            const key = `i18nSrc_${attr.replace('-', '')}`;
            if (!(key in el.dataset)) el.dataset[key] = el.getAttribute(attr);
            el.setAttribute(attr, t(el.dataset[key]));
        }
        if (el.hasAttribute('data-i18n-html')) {
            if (!('i18nSrcHtml' in el.dataset)) el.dataset.i18nSrcHtml = el.innerHTML.trim().replace(/\s+/g, ' ');
            el.innerHTML = t(el.dataset.i18nSrcHtml);
            return;
        }
        for (const node of el.childNodes) {
            if (node.nodeType === 3) {
                if (!i18nTextSrc.has(node)) i18nTextSrc.set(node, node.nodeValue);
                const src = i18nTextSrc.get(node);
                const key = src.trim().replace(/\s+/g, ' ');
                if (!key) continue;
                const lead = src.match(/^\s*/)[0], trail = src.match(/\s*$/)[0];
                node.nodeValue = lead + t(key) + trail;
            } else {
                walk(node);
            }
        }
    };
    walk(root);
}

